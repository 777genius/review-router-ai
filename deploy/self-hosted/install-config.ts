import assert from "node:assert/strict";
import {
  createHash,
  createPrivateKey,
  randomBytes,
  randomUUID,
} from "node:crypto";
import { lstat, mkdir, open, readFile, rename } from "node:fs/promises";
import { dirname } from "node:path";

export type Environment = Record<string, string>;
export type InstallSettings = {
  version: 1;
  sourceCommit: string;
  actionCommit: string;
  installationId: string;
  webUrl: string;
  apiUrl: string;
  proxy: "caddy" | "external";
  memory: "hindsight" | "disabled";
  permissionProfile: "provisioning" | "review-only";
};

// This is an immutable, installed runtime, not the moving workflow-v1 channel.
export const defaultActionCommit = "8328c2e6c3a2a7767a0667a2669982bc6ef71f64";
export const sha256 = (value: string) =>
  createHash("sha256").update(value).digest("hex");

export function publicOrigin(value: string): string {
  const url = new URL(value.includes("://") ? value : `https://${value}`);
  assert(
    url.protocol === "https:" &&
      !url.username &&
      !url.password &&
      !url.port &&
      url.pathname === "/" &&
      !url.search &&
      !url.hash &&
      /^(?=.{1,253}$)(?:[a-z0-9](?:[a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,63}$/i.test(
        url.hostname,
      ) &&
      !url.hostname.endsWith(".localhost") &&
      !url.hostname.endsWith(".local"),
    "Use a public HTTPS domain without a port, path, credentials, or query",
  );
  return url.origin;
}

export function readSettings(
  value: unknown,
  sourceCommit: string,
): InstallSettings {
  assert(
    value && typeof value === "object" && !Array.isArray(value),
    "Invalid installation state",
  );
  const state = value as Record<string, unknown>;
  assert(
    state.version === 1 &&
      state.sourceCommit === sourceCommit &&
      typeof state.actionCommit === "string" &&
      /^[a-f0-9]{40}$/.test(state.actionCommit) &&
      typeof state.installationId === "string" &&
      /^[a-f0-9]{16}$/.test(state.installationId) &&
      typeof state.webUrl === "string" &&
      typeof state.apiUrl === "string" &&
      ["caddy", "external"].includes(String(state.proxy)) &&
      ["hindsight", "disabled"].includes(String(state.memory)) &&
      ["provisioning", "review-only"].includes(String(state.permissionProfile)),
    "Installation state does not match this checkout; use the recorded revision to resume. Upgrades require the upgrade runbook",
  );
  assert(
    publicOrigin(state.webUrl) === state.webUrl &&
      publicOrigin(state.apiUrl) === state.apiUrl,
  );
  assert(
    state.webUrl !== state.apiUrl,
    "Web and API require different domains",
  );
  return state as InstallSettings;
}

/** Static single-line env assignments only. Never source operator input as shell. */
export function parseEnvironment(text: string): Environment {
  const result: Environment = {};
  for (const line of text.split(/\r?\n/)) {
    if (!line.trim() || line.trimStart().startsWith("#")) continue;
    const match = /^([A-Z][A-Z0-9_]*)=(.*)$/.exec(line);
    assert(match, "Unsupported environment assignment");
    const key = match[1]!,
      raw = match[2]!.trim();
    assert(!(key in result), `Duplicate environment key: ${key}`);
    let value = raw;
    if (raw.startsWith('"')) {
      const parsed: unknown = JSON.parse(raw);
      assert(typeof parsed === "string", `Invalid value for ${key}`);
      value = parsed;
    } else if (raw.startsWith("'")) {
      assert(
        raw.endsWith("'") && !raw.slice(1, -1).includes("'"),
        `Invalid value for ${key}`,
      );
      value = raw.slice(1, -1);
    }
    result[key] = value;
  }
  return result;
}

export function renderEnvironment(env: Readonly<Environment>): string {
  return (
    "# Generated by ReviewRouter self-hosted setup. Keep this file private.\n" +
    Object.entries(env)
      .map(([key, value]) => {
        assert(
          /^[A-Z][A-Z0-9_]*$/.test(key) && !/[\r\n\0']/.test(value),
          `Unsafe environment value: ${key}`,
        );
        // Literal values prevent Compose from expanding '$' in imported secrets.
        return `${key}='${value}'`;
      })
      .join("\n") +
    "\n"
  );
}

export async function privateDirectory(path: string): Promise<void> {
  await mkdir(path, { recursive: true, mode: 0o700 });
  const stat = await lstat(path);
  assert(
    stat.isDirectory() &&
      stat.uid === process.getuid?.() &&
      (stat.mode & 0o077) === 0,
    "Installation directory must be owned by you with mode 0700",
  );
}

export async function readPrivate(path: string): Promise<string | undefined> {
  try {
    const stat = await lstat(path);
    assert(
      stat.isFile() &&
        stat.uid === process.getuid?.() &&
        (stat.mode & 0o077) === 0,
      "Installation files must be owned by you with mode 0600; symlinks are not accepted",
    );
    return await readFile(path, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return undefined;
    throw error;
  }
}

export async function writePrivate(
  path: string,
  content: string,
): Promise<void> {
  await privateDirectory(dirname(path));
  await readPrivate(path); // Refuse to replace an unsafe file or a symlink.
  const temporary = `${path}.${randomUUID()}.tmp`;
  const file = await open(temporary, "wx", 0o600);
  try {
    await file.writeFile(content);
    await file.sync();
  } finally {
    await file.close();
  }
  await rename(temporary, path);
}

/** Called once, before any service starts. Resume reuses the saved file verbatim. */
export function createEnvironment(
  template: Environment,
  settings: InstallSettings,
  app: Environment,
  privateKey: string,
  operatorCredential: string,
): Environment {
  for (const key of [
    "GITHUB_APP_ID",
    "GITHUB_APP_CLIENT_ID",
    "GITHUB_APP_CLIENT_SECRET",
    "GITHUB_APP_SLUG",
    "GITHUB_WEBHOOK_SECRET",
  ]) {
    assert(app[key], `GitHub App profile is missing ${key}`);
  }
  assert(/^\d+$/.test(app.GITHUB_APP_ID!), "Invalid GitHub App ID");
  createPrivateKey(privateKey);
  const secret = () => randomBytes(32).toString("base64url");
  const keyring = (id: string) =>
    JSON.stringify([
      {
        keyId: id,
        secretBase64: randomBytes(32).toString("base64"),
        verifyUntil: null,
      },
    ]);
  const password = secret(),
    effectPassword = secret();
  const actionRef = `777genius/review-router@${settings.actionCommit}`;
  const env: Environment = {
    ...template,
    NODE_ENV: "production",
    AUTH_TRUST_HOST: "true",
    POSTGRES_DB: "review_router",
    POSTGRES_USER: "reviewrouter",
    POSTGRES_PASSWORD: password,
    DATABASE_URL: `postgresql://reviewrouter:${password}@postgres:5432/review_router?schema=public`,
    REVIEW_ROUTER_CODEX_EFFECT_AUTHORITY_DATABASE_URL: `postgresql://reviewrouter_codex_effect_authority:${effectPassword}@postgres:5432/review_router`,
    REVIEW_ROUTER_WEB_URL: settings.webUrl,
    REVIEW_ROUTER_PUBLIC_WEB_URL: settings.webUrl,
    REVIEW_ROUTER_API_URL: settings.apiUrl,
    REVIEW_ROUTER_PUBLIC_API_URL: settings.apiUrl,
    NEXTAUTH_URL: settings.webUrl,
    REVIEW_ROUTER_TLS_WEB_HOST: new URL(settings.webUrl).hostname,
    REVIEW_ROUTER_TLS_API_HOST: new URL(settings.apiUrl).hostname,
    REVIEW_ROUTER_IMAGE_TAG: `install-${settings.installationId}`,
    AUTH_SECRET: secret(),
    REVIEW_ROUTER_ACTION_SESSION_SECRET: secret(),
    REVIEW_ROUTER_TOKEN_ENCRYPTION_KEY: secret(),
    REVIEW_ROUTER_DATABASE_RECOVERY_WITNESS: secret(),
    REVIEW_ROUTER_GITHUB_APP_PERMISSION_PROFILE: settings.permissionProfile,
    REVIEW_ROUTER_ENABLE_WORKFLOW_PROVISIONING:
      settings.permissionProfile === "provisioning" ? "1" : "0",
    REVIEW_ROUTER_DISABLE_WORKFLOW_PROVISIONING:
      settings.permissionProfile === "provisioning" ? "0" : "1",
    REVIEW_ROUTER_ACTION_REF: actionRef,
    REVIEW_ROUTER_CODEX_ROTATING_ACTION_REF: actionRef,
    REVIEW_ROUTER_REVIEW_RUN_AUTHORIZATION_ACTIVE_KEY_ID: "selfhost-run-1",
    REVIEW_ROUTER_REVIEW_RUN_AUTHORIZATION_KEYS_JSON: keyring("selfhost-run-1"),
    REVIEW_ROUTER_REVIEW_V2_CAPABILITY_ACTIVE_KEY_ID: "selfhost-capability-1",
    REVIEW_ROUTER_REVIEW_V2_CAPABILITY_KEYS_JSON: keyring(
      "selfhost-capability-1",
    ),
    REVIEW_ROUTER_REVIEW_V2_CONTEXT_SESSION_SECRET_BASE64:
      randomBytes(32).toString("base64"),
    REVIEW_ROUTER_REVIEW_V2_CONTEXT_REPLAY_ACTIVE_KEY_ID: "selfhost-replay-1",
    REVIEW_ROUTER_REVIEW_V2_CONTEXT_REPLAY_KEYS_JSON: JSON.stringify([
      {
        keyId: "selfhost-replay-1",
        secretBase64: randomBytes(32).toString("base64"),
      },
    ]),
    REVIEW_ROUTER_REVIEW_V2_PROVIDER_VOTE_LANES_JSON: JSON.stringify(
      ["codex", "claude_code", "openrouter"].map((providerKind) => ({
        providerKind,
        providerVoteIdentityHash: randomBytes(32).toString("hex"),
      })),
    ),
    REVIEW_ROUTER_REVIEW_V2_OPERATOR_CREDENTIAL_SHA256:
      sha256(operatorCredential),
    REVIEW_ROUTER_MEMORY_PROVIDER:
      settings.memory === "disabled" ? "disabled" : "",
    REVIEW_ROUTER_CODEX_ROTATING_NEW_WORK_ADMISSION_ENABLED: "0",
    REVIEW_ROUTER_CODEX_ROTATING_SETUP_ISSUANCE_ENABLED: "0",
  };
  // Only App credentials are imported; an imported profile cannot override runtime controls.
  for (const key of [
    "GITHUB_APP_ID",
    "GITHUB_APP_CLIENT_ID",
    "GITHUB_APP_CLIENT_SECRET",
    "GITHUB_APP_SLUG",
    "GITHUB_WEBHOOK_SECRET",
  ])
    env[key] = app[key]!;
  env.GITHUB_CLIENT_ID = env.GITHUB_APP_CLIENT_ID!;
  env.GITHUB_CLIENT_SECRET = env.GITHUB_APP_CLIENT_SECRET!;
  env.GITHUB_APP_PRIVATE_KEY = privateKey
    .replaceAll("\r\n", "\n")
    .replaceAll("\n", "\\n");
  env.GITHUB_APP_PRIVATE_KEY_FILE = "";
  return env;
}

export function assertEnvironmentBinding(
  env: Environment,
  settings: InstallSettings,
  operator: string,
): void {
  assert(
    env.REVIEW_ROUTER_WEB_URL === settings.webUrl &&
      env.REVIEW_ROUTER_API_URL === settings.apiUrl &&
      env.REVIEW_ROUTER_CODEX_ROTATING_ACTION_REF ===
        `777genius/review-router@${settings.actionCommit}` &&
      env.REVIEW_ROUTER_REVIEW_V2_OPERATOR_CREDENTIAL_SHA256 ===
        sha256(operator),
    "Saved configuration does not match the installation. Preserve it and reconcile the mismatch before resuming",
  );
}

/** Admit only the first explicitly selected repository. Never reopen a saved pause. */
export function prepareRepositoryEnvironment(
  env: Environment,
  repository: string,
): Environment {
  assert(
    /^[A-Za-z0-9][A-Za-z0-9-]*\/[A-Za-z0-9_.-]+$/.test(repository),
    "Repository must be OWNER/REPO",
  );
  const cohort = env.REVIEW_ROUTER_CODEX_ROTATING_OAUTH_REPOSITORIES ?? "";
  const controls = [
    "REVIEW_ROUTER_CODEX_ROTATING_NEW_WORK_ADMISSION_ENABLED",
    "REVIEW_ROUTER_CODEX_ROTATING_SETUP_ISSUANCE_ENABLED",
  ];
  if (cohort) {
    assert(
      cohort === repository,
      "Saved Codex admission belongs to another repository; setup will not widen it",
    );
    assert(
      controls.every((key) => env[key] === "1"),
      "Codex setup or new work is paused; setup will not reopen the saved controls",
    );
    return env;
  }
  assert(
    controls.every((key) => !env[key] || env[key] === "0"),
    "Reconcile the existing Codex admission configuration before setup",
  );
  return {
    ...env,
    REVIEW_ROUTER_CODEX_ROTATING_OAUTH_REPOSITORIES: repository,
    REVIEW_ROUTER_CODEX_ROTATING_NEW_WORK_ADMISSION_ENABLED: "1",
    REVIEW_ROUTER_CODEX_ROTATING_SETUP_ISSUANCE_ENABLED: "1",
  };
}
