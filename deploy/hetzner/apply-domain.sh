#!/usr/bin/env bash
# Applies domain.env to all ReviewRouter domain consumers.
# Usage: sudo apply-domain.sh [--recreate]
#   --recreate  also rebuild web/api/worker containers so runtime env takes effect
set -euo pipefail

BASE=/etc/platform/projects/review-router
source "$BASE/domain.env"
: "${RR_URL_WEB:?domain.env: RR_URL_WEB missing}" "${RR_URL_API:?domain.env: RR_URL_API missing}"
: "${RR_HOSTS_WEB:?domain.env: RR_HOSTS_WEB missing}" "${RR_HOSTS_API:?domain.env: RR_HOSTS_API missing}"

# 1. Container runtime env (web/api/worker)
for f in web api worker; do
  p="$BASE/runtime-env/runtime-$f.env"
  sed -i \
    -e "s|^NEXTAUTH_URL=.*|NEXTAUTH_URL=\"$RR_URL_WEB\"|" \
    -e "s|^REVIEW_ROUTER_WEB_URL=.*|REVIEW_ROUTER_WEB_URL=\"$RR_URL_WEB\"|" \
    -e "s|^REVIEW_ROUTER_API_URL=.*|REVIEW_ROUTER_API_URL=\"$RR_URL_API\"|" \
    -e "s|^REVIEW_ROUTER_PUBLIC_API_URL=.*|REVIEW_ROUTER_PUBLIC_API_URL=\"$RR_URL_API\"|" \
    "$p"
  echo "updated $p"
done

# 2. Caddy site blocks (public web/api per host, loopback gateway, www redirects)
PRIMARY_WEB="${RR_HOSTS_WEB%% *}"
{
  echo "# GENERATED by apply-domain.sh from domain.env — do not edit by hand."
  echo "(rr-web-backend) {"
  echo "  import rr-public-review-pages"
  echo "  handle {"
  echo "    reverse_proxy 127.0.0.1:13082"
  echo "  }"
  echo "}"
  echo ""
  echo "(rr-api-backend) {"
  echo "  @newtest path /__newtest_v4/challenge /__newtest_v4/dispatch"
  echo "  handle @newtest {"
  echo "    reverse_proxy 127.0.0.1:13196"
  echo "  }"
  echo "  handle {"
  echo "    reverse_proxy 127.0.0.1:13083"
  echo "  }"
  echo "}"
  echo ""
  for h in $RR_HOSTS_WEB; do
    echo "$h {"
    if [[ "$h" == "$PRIMARY_WEB" ]]; then
      echo "  import rr-web-backend"
    else
      echo "  redir https://$PRIMARY_WEB{uri} 308"
    fi
    echo "}"
    echo ""
  done
  echo "$RR_HOSTS_API {"
  echo "  import rr-api-backend"
  echo "}"
  echo ""
  for h in $RR_HOSTS_API; do
    echo "https://$h:8443 {"
    echo "  bind 127.0.0.1"
    echo "  reverse_proxy 127.0.0.1:13195"
    echo "}"
    echo ""
  done
} > /etc/caddy/projects/review-router.caddy

{
  echo "# GENERATED by apply-domain.sh from domain.env — do not edit by hand."
  for h in $RR_HOSTS_WEB; do
    echo "www.$h {"
    echo "  redir https://$PRIMARY_WEB{uri} 308"
    echo "}"
    echo ""
  done
} > /etc/caddy/projects/review-router-www.caddy

{
  echo "# GENERATED by apply-domain.sh from domain.env — do not edit by hand."
  for h in $RR_HOSTS_API; do
    echo "https://$h:8443 {"
    echo "  bind 172.19.0.1"
    echo "  @usage {"
    echo "    method GET"
    echo "    path /v1/usage /v1/usage/*"
    echo "  }"
    echo "  handle @usage {"
    echo "    reverse_proxy 127.0.0.1:14171"
    echo "  }"
    echo "  @sdk path /v1/profiles /v1/accounts /v1/accounts/* /v1/operations/* /v1/policy-fences /v1/executions /v1/executions/* /internal/v1/run-access /v1/provider-connection-capabilities /v2/provider-connection-capabilities /v3/provider-connection-capabilities /v2/account-info/read /v2/account-models/read /v2/capabilities/account-lifecycle /v2/accounts /v2/accounts/* /v2/operations/* /v3/accounts/connections/begin /v3/accounts/connections/submit /v3/accounts/connections/poll /v3/accounts/* /v3/operations/* /v2/usage /v2/usage/* /v3/capabilities/account-limits /v3/account-limits/read /v1/capabilities/account-limits /v1/account-limits/read /v2/capabilities/account-limits /v2/account-limits/read /v1/account-models/read /v1/capabilities/account-limits-refresh /v1/account-limits/refresh"
    echo "  handle @sdk {"
    echo "    reverse_proxy 127.0.0.1:14171"
    echo "  }"
    echo "  handle {"
    echo "    respond 404"
    echo "  }"
    echo "}"
    echo ""
  done
} > /etc/caddy/projects/review-router-account-gateway-management.caddy

# 3. Validate and reload Caddy
caddy validate --config /etc/caddy/Caddyfile >/dev/null
systemctl reload caddy
echo "caddy reloaded"

if [[ "${1:-}" == "--recreate" ]]; then
  for c in $(docker ps --format "{{.Names}}" | grep "^rr-"); do
    project=$(docker inspect "$c" --format "{{index .Config.Labels \"com.docker.compose.project\"}}")
    wd=$(docker inspect "$c" --format "{{index .Config.Labels \"com.docker.compose.project.working_dir\"}}")
    files=$(docker inspect "$c" --format "{{index .Config.Labels \"com.docker.compose.project.config_files\"}}")
    svc=$(docker inspect "$c" --format "{{index .Config.Labels \"com.docker.compose.service\"}}")
    args=()
    IFS="," read -ra fl <<< "$files"
    for f in "${fl[@]}"; do args+=(-f "$f"); done
    (cd "$wd" && docker compose -p "$project" "${args[@]}" up -d --no-deps --no-build --pull never --force-recreate "$svc")
    echo "recreated $c"
  done
  echo "NOTE: verify GitHub App webhook + OAuth callback URLs and repo vars after a domain switch."
fi
