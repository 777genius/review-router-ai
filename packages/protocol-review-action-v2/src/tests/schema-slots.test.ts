import * as pinned171Manifest from "./fixtures/pinned171-provider-invocation-manifest-v1.js";
import {
  canonicalizeProviderInvocationManifestV1,
  providerInvocationManifestV1GoldenFixture,
} from "../index.js";
import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import { describe, expect, it } from "vitest";
import {
  reviewActionV2LegacySlot as legacy,
  reviewActionV2Pinned171Slot as pinned171,
  reviewActionV2ContractSlot,
  reviewActionV2SchemaSlot,
  canonicalizeReviewActionV2RequestForSlot,
  reviewActionV2PublishedSchemaDigest,
  type ReviewActionV2OperationId,
  type ReviewActionV2RequestMap,
} from "../index.js";
describe("finite immutable schema slots", () => {
  it("retains exact historical generated bytes", async () => {
    expect(
      await readFile(
        new URL("../generated/review-action-v2-legacy.ts", import.meta.url),
        "utf8",
      ),
    ).toBe(
      await readFile(
        new URL(
          "../../../../scripts/lib/review-action-v2-legacy-slot.ts.source",
          import.meta.url,
        ),
        "utf8",
      ),
    );
    expect(
      createHash("sha256")
        .update(
          await readFile(
            new URL("../generated/review-action-v2-legacy.ts", import.meta.url),
          ),
        )
        .digest("hex"),
    ).toBe("5be4f58794ec87eb4cf1d127189bdd12ca0df690cd2775ea0e10fd4246bd2e44");
    expect(legacy.reviewActionV2PublishedSchemaDigest).toBe(
      "32bb25cd3490660dbaeecaa168f162ba97ff171e2dfab69e1bd435bc2e1cf3d3",
    );
    expect(legacy.reviewActionV2CanonicalizerDigest).toBe(
      "12408727c244f65242534d3060983b87221715f2086631ab743c2c6f6248629a",
    );
    expect(legacy.reviewInvestigationExtensionV1.schemaDigest).toBe(
      "9ab22a39cc983b88ae50576ece6a777d72d904d09654d3f4c51a20fc13c29003",
    );
  });
  it("preserves the exact approved public171 source and every native request hash", async () => {
    const bytes = await readFile(
      new URL("../generated/review-action-v2-pinned171.ts", import.meta.url),
      "utf8",
    );
    expect(createHash("sha256").update(bytes).digest("hex")).toBe(
      "49a7018dbf1464e92947a57199217efa4a4ae6fa26fdb29388ac5907a460e782",
    );
    expect(bytes).toBe(
      await readFile(
        new URL(
          "../../../../scripts/lib/review-action-v2-pinned171-slot.ts.source",
          import.meta.url,
        ),
        "utf8",
      ),
    );
    expect(
      reviewActionV2ContractSlot(
        pinned171.reviewActionV2PublishedSchemaDigest,
        pinned171.reviewActionV2CanonicalizerDigest,
      ),
    ).toBe(pinned171);
    for (const { operationId } of pinned171.reviewActionV2Operations) {
      const request =
        pinned171.reviewActionV2GoldenFixtures[operationId].request;
      expect(
        pinned171.parseReviewActionV2Request(
          operationId as pinned171.ReviewActionV2OperationId,
          request,
        ).ok,
      ).toBe(true);
      const canonical = pinned171.canonicalizeReviewActionV2Request(
        operationId as pinned171.ReviewActionV2OperationId,
        request as unknown as pinned171.ReviewActionV2RequestMap[pinned171.ReviewActionV2OperationId],
      );
      expect(
        canonicalizeReviewActionV2RequestForSlot(
          operationId as ReviewActionV2OperationId,
          request as unknown as ReviewActionV2RequestMap[ReviewActionV2OperationId],
        ),
      ).toBe(canonical);
      expect(
        createHash("sha256")
          .update(
            legacy.canonicalizeReviewActionV2Request(
              operationId as legacy.ReviewActionV2OperationId,
              request as unknown as legacy.ReviewActionV2RequestMap[legacy.ReviewActionV2OperationId],
            ),
          )
          .digest("hex"),
      ).toBe(createHash("sha256").update(canonical).digest("hex"));
    }
    // Native functions really are identical; the published provider-manifest descriptor changed separately for OCR.
    expect(
      bytes
        .replace(
          pinned171.reviewActionV2CanonicalizerDigest,
          legacy.reviewActionV2CanonicalizerDigest,
        )
        .replace(
          pinned171.reviewInvestigationExtensionV1.canonicalizerDigest,
          legacy.reviewInvestigationExtensionV1.canonicalizerDigest,
        ),
    ).toBe(
      await readFile(
        new URL("../generated/review-action-v2-legacy.ts", import.meta.url),
        "utf8",
      ),
    );
  });
  it("preserves the old provider-manifest subset without treating OCR grammars as equivalent", async () => {
    expect(
      createHash("sha256")
        .update(
          await readFile(
            new URL(
              "./fixtures/pinned171-provider-invocation-manifest-v1.ts",
              import.meta.url,
            ),
          ),
        )
        .digest("hex"),
    ).toBe("6861cc12dd5df45140e7b0ee8c7bdf8adbe594b33748eedff6270ee48e9736cd");
    for (const providerKind of ["codex", "claude_code", "openrouter"]) {
      const input = {
        ...providerInvocationManifestV1GoldenFixture.input,
        providerKind,
      };
      expect(canonicalizeProviderInvocationManifestV1(input)).toEqual(
        pinned171Manifest.canonicalizeProviderInvocationManifestV1(input),
      );
    }
    const ocr = {
      ...providerInvocationManifestV1GoldenFixture.input,
      providerKind: "ocr",
    };
    expect(() =>
      pinned171Manifest.canonicalizeProviderInvocationManifestV1(ocr),
    ).toThrow("provider_kind_invalid");
    expect(() => canonicalizeProviderInvocationManifestV1(ocr)).not.toThrow();
  });
  it("parses and canonicalizes every old native operation with its frozen contract", () => {
    for (const descriptor of legacy.reviewActionV2Operations) {
      const operation = descriptor.operationId;
      const request = legacy.reviewActionV2GoldenFixtures[operation].request;
      expect(
        reviewActionV2SchemaSlot(
          request.schemaDigest,
        )!.parseReviewActionV2Request(
          operation as ReviewActionV2OperationId,
          request,
        ).ok,
      ).toBe(true);
      expect(
        canonicalizeReviewActionV2RequestForSlot(
          operation as ReviewActionV2OperationId,
          request as unknown as ReviewActionV2RequestMap[ReviewActionV2OperationId],
        ),
      ).toBe(
        legacy.canonicalizeReviewActionV2Request(
          operation as legacy.ReviewActionV2OperationId,
          request as unknown as legacy.ReviewActionV2RequestMap[legacy.ReviewActionV2OperationId],
        ),
      );
    }
    expect(reviewActionV2SchemaSlot("f".repeat(64))).toBeNull();
    expect(
      reviewActionV2SchemaSlot(reviewActionV2PublishedSchemaDigest),
    ).not.toBeNull();
  });
});
