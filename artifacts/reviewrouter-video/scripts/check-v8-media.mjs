import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
const video=process.argv[2];
assert.ok(video,'Usage: node check-v8-media.mjs <mp4>');
const x=spawnSync('ffprobe',['-v','error','-show_entries','format=duration,size','-show_entries','stream=codec_type,codec_name,width,height,avg_frame_rate','-of','json',video],{encoding:'utf8'});
assert.equal(x.status,0,x.stderr);
const m=JSON.parse(x.stdout);
const v=m.streams.find(s=>s.codec_type==='video');
const a=m.streams.find(s=>s.codec_type==='audio');
assert.ok(v,'Video stream missing');
assert.equal(v.width,1920);
assert.equal(v.height,1080);
assert.equal(v.avg_frame_rate,'30/1');
assert.equal(v.codec_name,'h264');
assert.ok(a,'Audio stream missing');
const duration=Number(m.format.duration);
assert.ok(duration>33.85 && duration<34.2,'Unexpected duration '+duration);
const bytes=Number(m.format.size);
assert.ok(bytes>200000,'Suspiciously small video '+bytes);
console.log('[V8 verified]',{duration,bytes,video:v.codec_name,audio:a.codec_name});
